const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.HOME_PREVIEW_URL || 'http://127.0.0.1:8912/';
const output = process.env.HOME_EVIDENCE_DIR || '/tmp/nice-home-evidence';
fs.mkdirSync(output,{recursive:true});
(async()=>{
  const browser=await chromium.launch({headless:true});
  let checks=0;
  for(const width of [390,1440]) for(const locale of ['zh-Hans','zh-Hant','ja','en']){
    const context=await browser.newContext({viewport:{width,height:950},locale});
    const page=await context.newPage();
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    // No analytics events from candidate testing.
    await page.route('**/analytics.nice.okinawa/**',route=>route.abort());
    await page.goto(base,{waitUntil:'networkidle'});
    assert.equal(await page.locator('html').getAttribute('lang'),locale);
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${width}/${locale} overflow`);
    assert.equal(await page.locator('#news .tips-card').count(),3);
    assert.equal(await page.locator('#travel .cards > a').count(),5);
    assert.equal(await page.locator('.gateway a').count(),3);
    for(const link of await page.locator('a[href^="#"]').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('href')))) assert(await page.locator(link).count(),link);
    const routes=await page.locator('[data-route]').evaluateAll(nodes=>nodes.map(n=>n.href));
    for(const url of routes) assert.equal((await page.request.get(url)).status(),200,url);
    await page.locator('#submitBtn').click();
    assert((await page.locator('#form-status').innerText()).length>10);
    await page.locator('#cf-name').fill('Preview Test');
    await page.locator('#cf-email').fill('invalid');
    await page.locator('#cf-message').fill('Local test only');
    await page.locator('#waBtn').click();
    assert.equal(await page.evaluate(()=>document.activeElement.id),'cf-email');
    await page.locator('#cf-email').fill('preview@example.invalid');
    await page.evaluate(()=>{window.open=(url)=>{window.__outgoing=url;return null;}});
    await page.locator('#waBtn').click();
    assert((await page.evaluate(()=>window.__outgoing)).startsWith('https://wa.me/817089523968?text='));
    await page.locator('#cf-name').fill('');await page.locator('#cf-email').fill('');await page.locator('#cf-message').fill('');
    await page.evaluate(()=>{document.getElementById('form-status').textContent='';document.documentElement.style.scrollBehavior='auto';document.activeElement.blur();scrollTo(0,0)});
    await page.screenshot({path:path.join(output,`${width}-${locale}.png`),fullPage:true});
    await page.selectOption('#language','ja');
    assert.equal(await page.locator('html').getAttribute('lang'),'ja');
    await page.goto(base+'?lang=en');
    assert.equal(await page.locator('html').getAttribute('lang'),'ja');
    assert.deepEqual(errors,[]);
    await context.close();checks++;
  }
  const context=await browser.newContext({viewport:{width:320,height:800},locale:'en-US'});
  const page=await context.newPage();await page.goto(base+'?lang=zh-Hans');
  assert.equal(await page.locator('html').getAttribute('lang'),'zh-Hans');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await context.close();
  const blocked=await browser.newContext({locale:'ja-JP'});
  await blocked.addInitScript(()=>Object.defineProperty(window,'localStorage',{get(){throw new Error('blocked')}}));
  const p=await blocked.newPage();await p.goto(base);assert.equal(await p.locator('html').getAttribute('lang'),'ja');
  await p.selectOption('#language','en');assert.equal(await p.locator('html').getAttribute('lang'),'en');
  await blocked.close();await browser.close();
  console.log(`PASS: ${checks} viewport × language cases; 320px; blocked storage; local links; news; form validation; intercepted WhatsApp; persistence. Screenshots: ${output}`);
})().catch(e=>{console.error(e);process.exitCode=1});
