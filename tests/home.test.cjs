const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.join(__dirname,'..');
const source = fs.readFileSync(path.join(root,'assets/js/ui-language-resolver.js'),'utf8');
const context = {URL}; vm.createContext(context); vm.runInContext(source,context);
const r = context.SinkolaboUiLanguage;
const resolve = (saved,url,languages) => r.resolveUiLanguage({storage:{getItem:()=>saved},url:'https://nice.okinawa/'+url,languages});
assert.equal(resolve('ja','?lang=en',['zh-TW']),'ja');
assert.equal(resolve(null,'?lang=zh-Hans',['ja']),'zh-Hans');
assert.equal(resolve(null,'?ui=zh-Hant',['ja']),'zh-Hant');
for (const tag of ['zh-TW','ZH-hANT-TW','zh-HK','zh-MO']) assert.equal(resolve(null,'',[tag]),'zh-Hant');
for (const tag of ['zh','zh-CN','zh-Hans','zh-SG']) assert.equal(resolve(null,'',[tag]),'zh-Hans');
assert.equal(resolve(null,'',['ja-JP']),'ja');
assert.equal(resolve(null,'',['en-US','zh-CN']),'en');
assert.equal(resolve(null,'',['unknown']),'en');
assert.equal(r.resolveUiLanguage({storage:{getItem(){throw Error('blocked')}},url:'https://nice.okinawa/?lang=ja',languages:['en']}),'ja');
const html = fs.readFileSync(path.join(root,'index.html'),'utf8');
const copy = JSON.parse(fs.readFileSync(path.join(root,'content/home/copy.json')));
for(const m of html.matchAll(/data-i18n="([^"]+)"/g)) assert.equal(copy[m[1]].length,4,m[1]);
for(const [key,row] of Object.entries(copy)) assert(row.every(s=>typeof s==='string'&&s.trim()),key);
assert(!/navigator\.languages?\b/.test(html+fs.readFileSync(path.join(root,'assets/js/home.js'),'utf8')));
assert(html.includes('TRAVEL-TRANSPORT-20261104-01 START'));
assert(html.includes('naha-foreign-talent-training-grant-2026'));
assert(html.includes('okinawa-tourism-h1-2026'));
assert(!html.includes('site-kerama-link'));
console.log('PASS: resolver precedence, mappings, blocked storage, copy completeness, news preservation, no page-local detection.');
